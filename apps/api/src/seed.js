/**
 * 写入种子数据。已写入过（seed_version 达标）时直接跳过。
 * 使用 INSERT OR IGNORE + 固定 id，保证即使中途异常也不会产生重复数据。
 * @param {import('node:sqlite').DatabaseSync} db
 * @returns {boolean} 本次是否真的写入了种子数据
 */
export function seedDatabase(db) {
  const current = db.prepare("SELECT value FROM meta WHERE key = 'seed_version'").get();
  if (current && Number(current.value) >= SEED_VERSION) {
    return false;
  }

  const insertCategory = db.prepare(
    'INSERT OR IGNORE INTO categories (id, name, slug, icon, sort_order) VALUES (?, ?, ?, ?, ?)',
  );
  const insertPost = db.prepare(
    `INSERT OR IGNORE INTO posts
       (id, title, content, cover, category, author_name, author_avatar, likes, tags, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
  );
  const insertComment = db.prepare(
    'INSERT OR IGNORE INTO comments (id, post_id, author_name, content, created_at) VALUES (?, ?, ?, ?, ?)',
  );
  const insertArticle = db.prepare(
    `INSERT OR IGNORE INTO articles
       (id, title, summary, content, cover, category, read_count, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
  );
  const setMeta = db.prepare(
    `INSERT INTO meta (key, value) VALUES ('seed_version', ?)
     ON CONFLICT(key) DO UPDATE SET value = excluded.value`,
  );

  db.exec('BEGIN');
  try {
    for (const category of CATEGORIES) {
      insertCategory.run(category.id, category.name, category.slug, category.icon, category.sortOrder);
    }

    let commentId = 1;
    for (const post of POSTS) {
      insertPost.run(
        post.id,
        post.title,
        post.content,
        coverSvg(post.emoji, post.category),
        post.category,
        post.authorName,
        avatarSvg(post.authorName),
        post.likes,
        JSON.stringify(post.tags ?? []),
        post.createdAt,
      );
      for (const comment of post.comments ?? []) {
        insertComment.run(commentId++, post.id, comment.authorName, comment.content, comment.createdAt);
      }
    }

    for (const article of ARTICLES) {
      insertArticle.run(
        article.id,
        article.title,
        article.summary,
        article.content,
        coverSvg(article.emoji, article.category),
        article.category,
        article.readCount,
        article.createdAt,
      );
    }

    setMeta.run(String(SEED_VERSION));
    db.exec('COMMIT');
  } catch (error) {
    db.exec('ROLLBACK');
    throw error;
  }

  return true;
}
